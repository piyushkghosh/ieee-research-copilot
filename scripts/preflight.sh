#!/usr/bin/env bash
# preflight.sh — POSIX entry point. Prefers the Node detector; falls back to a
# minimal bash probe when Node is absent so a bare machine still gets a report.
set -u

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
STATE="$ROOT/research/.state"
OUT="$STATE/toolkit.md"

if command -v node >/dev/null 2>&1; then
  exec node "$ROOT/scripts/preflight.mjs" "$@"
fi

# ---- fallback: no Node ----
mkdir -p "$STATE"
find_tool() { command -v "$1" >/dev/null 2>&1; }

tex_engine=""
for e in pdflatex xelatex lualatex; do
  if find_tool "$e"; then tex_engine="$e"; break; fi
done

ieee_cls="missing"
if find_tool kpsewhich && kpsewhich IEEEtran.cls >/dev/null 2>&1; then ieee_cls="present"; fi

if [ -n "$tex_engine" ] && [ "$ieee_cls" = "present" ]; then
  MODE="full-tex"; REASON="TeX engine ($tex_engine) and IEEEtran.cls resolved."
elif [ -z "$tex_engine" ]; then
  MODE="degraded-markdown"; REASON="No TeX engine (pdflatex/xelatex/lualatex) on PATH."
else
  MODE="degraded-markdown"; REASON="TeX engine present but IEEEtran.cls not found (run scripts/bootstrap.sh --tex-only)."
fi

{
  echo "# Toolchain report"
  echo
  echo "<!-- Generated by scripts/preflight.sh (no-Node fallback). Install Node and re-run scripts/preflight.mjs for the full report. -->"
  echo
  echo "- Generated: $(date -u +%Y-%m-%dT%H:%M:%SZ)"
  echo "- Platform: $(uname -s)/$(uname -m)"
  echo "- **MODE: $MODE**"
  echo "- Reason: $REASON"
  echo
  echo "## Tools"
  echo
  echo "| Tool | Present |"
  echo "|---|---|"
  for t in node npm npx git python3 pip3 pdflatex xelatex lualatex latexmk bibtex biber gs pdftotext pdfinfo firefox chromium google-chrome inkscape rsvg-convert pandoc; do
    if find_tool "$t"; then echo "| $t | yes |"; else echo "| $t | **missing** |"; fi
  done
  echo
  echo "## Rules for agents"
  echo "- Never assume a tool exists; re-read this file every loop."
  echo "- In degraded mode write Markdown to research/manuscript/ and mark the compile gate SKIPPED (no TeX)."
  echo "- Never run sudo. Report the exact install command and let the user decide."
} > "$OUT"

echo "MODE: $MODE — $REASON"
echo "wrote $OUT"
